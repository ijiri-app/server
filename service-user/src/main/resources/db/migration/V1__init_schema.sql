-- service-user 스키마: 회원, 세션(refresh token), 이메일 인증, 보유 차량, 관심 차종.
-- enum 컬럼(provider, role 등)에는 CHECK 제약을 두지 않는다. 값 검증은 Kotlin enum 이 한다.
-- 다른 서비스의 데이터(게시물, 사진, 차종 마스터)는 id 로만 가리키고 FK 는 두지 않는다

CREATE TABLE member
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at         TIMESTAMP(6) NOT NULL,
    updated_at         TIMESTAMP(6) NOT NULL,
    email              VARCHAR(255),
    nickname           VARCHAR(100) NOT NULL,
    password           VARCHAR(60),
    profile_image_url  VARCHAR(500),
    status_message     VARCHAR(50),
    provider           VARCHAR(20)  NOT NULL,
    provider_member_id VARCHAR(255) NOT NULL,
    role               VARCHAR(20)  NOT NULL,
    deleted_at         TIMESTAMP(6),
    suspended_until    TIMESTAMP(6),
    CONSTRAINT uk_member_provider_provider_member_id UNIQUE (provider, provider_member_id),
    CONSTRAINT uk_member_nickname UNIQUE (nickname)
);

CREATE INDEX idx_member_deleted_at ON member (deleted_at);

-- 계정당 세션 1개 (member_id 유니크). 토큰은 SHA-256 해시만 저장한다
CREATE TABLE refresh_token
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id  BIGINT       NOT NULL,
    token_hash VARCHAR(64)  NOT NULL,
    expires_at TIMESTAMP(6) NOT NULL,
    session_id VARCHAR(36)  NOT NULL,
    CONSTRAINT uk_refresh_token_member_id UNIQUE (member_id),
    CONSTRAINT uk_refresh_token_token_hash UNIQUE (token_hash),
    CONSTRAINT uk_refresh_token_session_id UNIQUE (session_id)
);

-- 이메일 + 용도(가입, 비밀번호 재설정)당 한 줄. 코드를 확인하면 verificationToken 해시를 저장한다
CREATE TABLE email_verification
(
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at              TIMESTAMP(6) NOT NULL,
    updated_at              TIMESTAMP(6) NOT NULL,
    email                   VARCHAR(255) NOT NULL,
    purpose                 VARCHAR(20)  NOT NULL,
    code                    VARCHAR(6)   NOT NULL,
    sent_at                 TIMESTAMP(6) NOT NULL,
    expires_at              TIMESTAMP(6) NOT NULL,
    attempt_count           INTEGER      NOT NULL,
    verified_at             TIMESTAMP(6),
    verification_token_hash VARCHAR(64),
    CONSTRAINT uk_email_verification_email_purpose UNIQUE (email, purpose)
);

-- 보유 차량: 트림 단위, 연식 필수, 별칭, 지금 타는 차(OWNED)·이전 차량(PAST)
CREATE TABLE owned_car
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at        TIMESTAMP(6) NOT NULL,
    updated_at        TIMESTAMP(6) NOT NULL,
    member_id         BIGINT       NOT NULL,
    car_model_id      BIGINT       NOT NULL,
    car_generation_id BIGINT       NOT NULL,
    car_trim_id       BIGINT       NOT NULL,
    model_year        INTEGER      NOT NULL,
    build_style       VARCHAR(20),
    nickname          VARCHAR(20),
    status            VARCHAR(20)  NOT NULL
);

CREATE INDEX idx_owned_car_member_id ON owned_car (member_id);

CREATE TABLE member_interest_car
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at    TIMESTAMP(6) NOT NULL,
    updated_at    TIMESTAMP(6) NOT NULL,
    member_id     BIGINT       NOT NULL,
    car_model_id  BIGINT       NOT NULL,
    display_order INTEGER      NOT NULL,
    CONSTRAINT uk_member_interest_car_member_id_car_model_id UNIQUE (member_id, car_model_id)
);

CREATE INDEX idx_member_interest_car_member_id ON member_interest_car (member_id);
