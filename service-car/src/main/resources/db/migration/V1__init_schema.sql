-- service-car 스키마: 차종 마스터(모델, 세대, 트림)와 부품, 브랜드, 별칭, 차종별 부품 사용 수.
-- enum 컬럼에는 CHECK 제약을 두지 않는다. 값 검증은 Kotlin enum 이 한다

-- 부품·브랜드 검색에서 오타·부분 일치를 찾기 위한 trigram 유사도
CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE car_model
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand         VARCHAR(50)  NOT NULL,
    name          VARCHAR(100) NOT NULL,
    is_core       BOOLEAN      NOT NULL,
    image_url     VARCHAR(500),
    hidden        BOOLEAN      NOT NULL,
    display_order INTEGER      NOT NULL,
    CONSTRAINT uk_car_model_brand_name UNIQUE (brand, name)
);

CREATE TABLE car_generation
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    car_model_id BIGINT      NOT NULL,
    code         VARCHAR(50) NOT NULL,
    start_year   INTEGER     NOT NULL,
    end_year     INTEGER,
    CONSTRAINT uk_car_generation_car_model_id_code UNIQUE (car_model_id, code)
);

CREATE TABLE car_trim
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    car_generation_id BIGINT       NOT NULL,
    name              VARCHAR(100) NOT NULL,
    CONSTRAINT uk_car_trim_car_generation_id_name UNIQUE (car_generation_id, name)
);

CREATE TABLE brand
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMP(6) NOT NULL,
    updated_at      TIMESTAMP(6) NOT NULL,
    name            VARCHAR(50)  NOT NULL,
    normalized_name VARCHAR(50)  NOT NULL,
    CONSTRAINT uk_brand_normalized_name UNIQUE (normalized_name)
);

CREATE INDEX idx_brand_normalized_name ON brand USING gin (normalized_name gin_trgm_ops);

-- 브랜드 없는 부품(자작 등)도 이름이 같으면 하나로 본다
CREATE TABLE part
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMP(6) NOT NULL,
    updated_at      TIMESTAMP(6) NOT NULL,
    brand_id        BIGINT,
    name            VARCHAR(100) NOT NULL,
    normalized_name VARCHAR(100) NOT NULL,
    category        VARCHAR(20)  NOT NULL,
    status          VARCHAR(20)  NOT NULL,
    use_count       INTEGER      NOT NULL,
    CONSTRAINT uk_part_brand_id_normalized_name UNIQUE NULLS NOT DISTINCT (brand_id, normalized_name)
);

CREATE INDEX idx_part_normalized_name ON part USING gin (normalized_name gin_trgm_ops);

-- 관리자 합치기로 사라진 부품 이름이 별칭으로 남는다. 검색은 별칭도 찾는다
CREATE TABLE part_alias
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    part_id         BIGINT       NOT NULL,
    name            VARCHAR(150) NOT NULL,
    normalized_name VARCHAR(150) NOT NULL,
    CONSTRAINT uk_part_alias_part_id_normalized_name UNIQUE (part_id, normalized_name)
);

CREATE INDEX idx_part_alias_normalized_name ON part_alias USING gin (normalized_name gin_trgm_ops);

-- 차종별 부품 사용 수. 부품 검색에서 같은 차종에 자주 달린 부품을 위로 올린다
CREATE TABLE part_car_model_usage
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    part_id      BIGINT  NOT NULL,
    car_model_id BIGINT  NOT NULL,
    use_count    INTEGER NOT NULL,
    CONSTRAINT uk_part_car_model_usage_part_id_car_model_id UNIQUE (part_id, car_model_id)
);
