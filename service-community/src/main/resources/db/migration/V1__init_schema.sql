-- service-community 스키마: 게시물 묶음(post, post_image, post_part, post_part_tag), 위시리스트, 차단, 신고.
-- 게시물 묶음 안에서만 FK 를 두고, 다른 서비스의 데이터(회원, 보유 차량, 차종, 부품, 사진)는 id 로만 가리킨다.
-- enum 컬럼에는 CHECK 제약을 두지 않는다. 값 검증은 Kotlin enum 이 한다

CREATE TABLE post
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at        TIMESTAMP(6) NOT NULL,
    updated_at        TIMESTAMP(6) NOT NULL,
    member_id         BIGINT       NOT NULL,
    owned_car_id      BIGINT       NOT NULL,
    car_model_id      BIGINT       NOT NULL,
    car_generation_id BIGINT       NOT NULL,
    car_trim_id       BIGINT       NOT NULL,
    model_year        INTEGER      NOT NULL,
    build_style       VARCHAR(20)  NOT NULL,
    content           VARCHAR(1000),
    status            VARCHAR(20)  NOT NULL,
    part_count        INTEGER      NOT NULL
);

CREATE INDEX idx_post_member_id ON post (member_id);
CREATE INDEX idx_post_owned_car_id ON post (owned_car_id);
CREATE INDEX idx_post_status_car_model_id ON post (status, car_model_id);

CREATE TABLE post_image
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id       BIGINT       NOT NULL REFERENCES post (id),
    image_key     VARCHAR(100) NOT NULL,
    url           VARCHAR(500) NOT NULL,
    width         INTEGER      NOT NULL,
    height        INTEGER      NOT NULL,
    display_order INTEGER      NOT NULL,
    CONSTRAINT uk_post_image_image_key UNIQUE (image_key)
);

CREATE INDEX idx_post_image_post_id ON post_image (post_id);

-- 게시물에 달린 부품(postPartId). 위시리스트는 이 id 를 담는다
CREATE TABLE post_part
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id       BIGINT      NOT NULL REFERENCES post (id),
    part_id       BIGINT      NOT NULL,
    category      VARCHAR(20) NOT NULL,
    display_order INTEGER     NOT NULL
);

CREATE INDEX idx_post_part_post_id ON post_part (post_id);
CREATE INDEX idx_post_part_part_id ON post_part (part_id);

CREATE TABLE post_part_tag
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_part_id  BIGINT           NOT NULL REFERENCES post_part (id),
    post_image_id BIGINT           NOT NULL REFERENCES post_image (id),
    x             DOUBLE PRECISION NOT NULL,
    y             DOUBLE PRECISION NOT NULL
);

CREATE INDEX idx_post_part_tag_post_part_id ON post_part_tag (post_part_id);
CREATE INDEX idx_post_part_tag_post_image_id ON post_part_tag (post_image_id);

-- post_id, post_author_id 는 목록·담기 수 집계를 위해 담을 때 복사해 둔다. 탈퇴한 회원의 담기는 hidden
CREATE TABLE wishlist_item
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at     TIMESTAMP(6) NOT NULL,
    updated_at     TIMESTAMP(6) NOT NULL,
    member_id      BIGINT       NOT NULL,
    post_part_id   BIGINT       NOT NULL,
    post_id        BIGINT       NOT NULL,
    post_author_id BIGINT       NOT NULL,
    hidden         BOOLEAN      NOT NULL,
    CONSTRAINT uk_wishlist_item_member_id_post_part_id UNIQUE (member_id, post_part_id)
);

CREATE INDEX idx_wishlist_item_post_part_id ON wishlist_item (post_part_id);
CREATE INDEX idx_wishlist_item_post_id ON wishlist_item (post_id);
CREATE INDEX idx_wishlist_item_post_author_id ON wishlist_item (post_author_id);

CREATE TABLE member_block
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    blocker_id BIGINT       NOT NULL,
    blocked_id BIGINT       NOT NULL,
    CONSTRAINT uk_member_block_blocker_id_blocked_id UNIQUE (blocker_id, blocked_id)
);

CREATE INDEX idx_member_block_blocked_id ON member_block (blocked_id);

CREATE TABLE report
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at       TIMESTAMP(6) NOT NULL,
    updated_at       TIMESTAMP(6) NOT NULL,
    reporter_id      BIGINT       NOT NULL,
    target_type      VARCHAR(20)  NOT NULL,
    target_id        BIGINT       NOT NULL,
    target_member_id BIGINT       NOT NULL,
    reason           VARCHAR(30)  NOT NULL,
    detail           VARCHAR(300),
    status           VARCHAR(20)  NOT NULL,
    action           VARCHAR(20),
    resolved_by      BIGINT,
    resolved_at      TIMESTAMP(6),
    CONSTRAINT uk_report_reporter_id_target_type_target_id UNIQUE (reporter_id, target_type, target_id)
);

CREATE INDEX idx_report_status_target_type_target_id ON report (status, target_type, target_id);
CREATE INDEX idx_report_target_member_id ON report (target_member_id);
